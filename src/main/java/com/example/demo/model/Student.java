package com.example.demo.model;
public class Student 
{
	private int id;
	private String uname;
	private String uphy;
	private String uche;
	private String umath;
	public int getId() {
		return id;
	}
	public void setId(int id) {
		this.id = id;
	}
	public String getUname() {
		return uname;
	}
	public void setUname(String uname) {
		this.uname = uname;
	}
	public String getUphy() {
		return uphy;
	}
	public void setUphy(String uphy) {
		this.uphy = uphy;
	}
	public String getUche() {
		return uche;
	}
	public void setUche(String uche) {
		this.uche = uche;
	}
	public String getUmath() {
		return umath;
	}
	public void setUmath(String umath) {
		this.umath = umath;
	}
	
}
